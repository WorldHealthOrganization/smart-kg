#!/usr/bin/env node
// Turns an extracted graph document into Cypher, so the DATA can be loaded into Neo4j and not
// only the schema.
//
// The ontology exports carry the type graph -- 40 classes and the 95 edges licensed between them.
// That answers "what may exist". This answers "what does exist": 387 nodes and 516 edges extracted
// from smart-base. They are deliberately kept apart in the store, by label:
//
//   :KGClass    a class in the ontology          (from ontology/generated/*.cypher)
//   :Instance   a thing found in a real artefact (from here)
//
// On an :Instance, `id` is the IRI and is the node's identity. Where a class also declares a
// domain property called id, that value is stored as `localId`.
//
// so that a query can never accidentally traverse from a persona to the idea of a persona. Every
// :Instance also carries `layer` (l1 | l2 | l2-bpmn | l2-dmn) and a label for its type, which is
// what makes a single subgraph selectable in the browser.
//
//   node tools/build-instance-cypher.mjs examples/*.json --out ontology/generated/instances.cypher

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, basename } from "node:path";

// Cypher string literals cannot span lines, and FSH descriptions are multi-line markdown. Without
// escaping the newlines the file loads as a syntax error at the first persona -- and the file looks
// fine until you try it.
const cy = (s) => String(s)
  .replace(/\\/g, "\\\\")
  .replace(/'/g, "\\'")
  .replace(/\r/g, "\\r")
  .replace(/\n/g, "\\n")
  .replace(/\t/g, "\\t");

/** Neo4j labels may not contain hyphens unquoted, and every class id here does. */
const label = (t) => "`" + String(t).replace(/`/g, "") + "`";

/**
 * Neo4j properties are primitives or arrays of one primitive type. A dmn-rule's `conditions` is an
 * array of objects; storing it as a JSON string keeps it inspectable in the browser rather than
 * dropping it, and nothing queries into it -- if something ever needs to, that is the signal the
 * cells should have been nodes after all.
 */
function flatten(props = {}) {
  const out = [];
  for (const [k, v] of Object.entries(props)) {
    if (v === null || v === undefined) continue;
    // `id` is the MERGE key and holds the IRI. Several classes ALSO declare a domain property
    // called id -- a DAK's is "smart.who.int.base", a persona's is its FSH instance name -- and
    // writing that into n.id would rename the node out from under the uniqueness constraint and
    // break every MATCH that follows. Keep the domain value under localId.
    if (k === "id") { out.push(`localId: '${cy(v)}'`); continue; }
    if (typeof v === "string" || typeof v === "number" || typeof v === "boolean") {
      out.push(`${k}: ${typeof v === "string" ? `'${cy(v)}'` : v}`);
    } else if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
      out.push(`${k}: [${v.map((x) => `'${cy(x)}'`).join(", ")}]`);
    } else if (Array.isArray(v) && v.length === 0) {
      continue;
    } else {
      out.push(`${k}: '${cy(JSON.stringify(v))}'`);
    }
  }
  return out;
}

const layerOf = (doc) =>
  /\/(l\d+(?:-[a-z0-9]+)*)\.context\.jsonld$/.exec(doc["@context"] ?? "")?.[1] ?? "unknown";

export function buildInstanceCypher(docs) {
  const L = [
    "// WHO SMART Guidelines knowledge graph -- INSTANCE DATA.",
    "// Generated by tools/build-instance-cypher.mjs. Do not edit.",
    "//",
    "// This is what was found in real artefacts, as opposed to what the ontology permits. Nodes",
    "// are labelled :Instance (never :KGClass) plus their type, and carry `layer` so one subgraph",
    "// can be selected on its own. See docs/VISUALIZING.md for the queries.",
    "//",
    "// Every statement is MERGE, so re-running is safe. Load AFTER the ontology if you want both.",
    "",
    "CREATE CONSTRAINT instance_id IF NOT EXISTS",
    "FOR (n:Instance) REQUIRE n.id IS UNIQUE;",
    "",
  ];

  // One IRI can be described by two layers -- an l1:external-artifact and the l2-bpmn:bpmn-definitions
  // that elaborates it are the same file. MERGE on id and add the second type as another label,
  // rather than letting the later document overwrite the earlier one's type.
  const seen = new Map();
  let nodeCount = 0;
  let edgeCount = 0;

  for (const doc of docs) {
    const layer = layerOf(doc);
    L.push(`// ---------- ${layer}: ${(doc.nodes ?? []).length} nodes, ${(doc.edges ?? []).length} edges ----------`);
    for (const n of doc.nodes ?? []) {
      const props = flatten({
        ...n.properties,
        label: n.label,
        layer,
        derivation: n.derivation,
        ...(n.skill ? { skill: n.skill } : {}),
      });
      if (seen.has(n.id) && seen.get(n.id) !== n.type) {
        // Second description of one artefact. Add the label, keep both layers visible.
        L.push(`MATCH (n:Instance {id:'${cy(n.id)}'}) SET n:${label(n.type)}, ` +
               `n.layers = coalesce(n.layers, []) + '${cy(layer)}';`);
      } else {
        L.push(`MERGE (n:Instance:${label(n.type)} {id:'${cy(n.id)}'}) ` +
               `SET n += {${props.join(", ")}};`);
        nodeCount++;
      }
      seen.set(n.id, n.type);
    }
    L.push("");
    for (const e of doc.edges ?? []) {
      const props = flatten({
        ...e.properties,
        ...(e.qualifier ? { qualifier: e.qualifier } : {}),
        derivation: e.derivation,
        layer,
      });
      L.push(`MATCH (s:Instance {id:'${cy(e.source)}'}), (t:Instance {id:'${cy(e.target)}'}) ` +
             `MERGE (s)-[r:${e.predicate.toUpperCase()}]->(t) SET r += {${props.join(", ")}};`);
      edgeCount++;
    }
    L.push("");
  }

  // Cypher is emitted one statement per line, so a raw newline or an odd number of unescaped
  // quotes means a file that looks fine and fails on load. Caught here rather than in Neo4j.
  for (const [i, line] of L.entries()) {
    if (!line || line.startsWith("//")) continue;
    if (/[\n\r]/.test(line)) {
      throw new Error(`line ${i + 1} contains a raw newline; cy() must escape it:\n  ${line.slice(0, 120)}`);
    }
    const quotes = (line.replace(/\\\\/g, "").replace(/\\'/g, "").match(/'/g) ?? []).length;
    if (quotes % 2) {
      throw new Error(`line ${i + 1} has an odd number of unescaped quotes:\n  ${line.slice(0, 120)}`);
    }
  }

  L.push(
    "// Verification. Node and relationship counts per layer:",
    "// MATCH (n:Instance) RETURN n.layer AS layer, count(*) AS nodes ORDER BY layer;",
    `// Expect ${nodeCount} nodes and ${edgeCount} relationships in total.`);
  return { text: L.join("\n") + "\n", nodeCount, edgeCount };
}

function main() {
  const outIdx = process.argv.indexOf("--out");
  const out = outIdx === -1 ? null : process.argv[outIdx + 1];
  const files = process.argv.slice(2).filter((a, i) => !a.startsWith("--")
    && (outIdx === -1 || process.argv.indexOf(a) !== outIdx + 1));
  if (!files.length) {
    console.error("usage: build-instance-cypher.mjs <doc.json>... [--out <path>]");
    process.exit(2);
  }
  // Load in layer order so the opaque description is written before the elaboration that refines it.
  const order = ["l1", "l2", "l2-bpmn", "l2-dmn"];
  const docs = files.map((f) => JSON.parse(readFileSync(f, "utf8")))
    .sort((a, b) => order.indexOf(layerOf(a)) - order.indexOf(layerOf(b)));

  const { text, nodeCount, edgeCount } = buildInstanceCypher(docs);
  if (out) { mkdirSync(dirname(out), { recursive: true }); writeFileSync(out, text, "utf8"); }
  else process.stdout.write(text);
  console.error(`${nodeCount} nodes, ${edgeCount} relationships from ${docs.length} document(s)` +
                (out ? ` -> ${out}` : ""));
}

if (process.argv[1] && import.meta.url.endsWith(basename(process.argv[1]))) main();
